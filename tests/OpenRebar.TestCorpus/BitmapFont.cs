using SixLabors.ImageSharp;
using SixLabors.ImageSharp.PixelFormats;

namespace OpenRebar.TestCorpus;

/// <summary>
/// 5×7 glyphs for the legend labels. Enough for <c>20@150</c> and <c>10mm/px</c>.
/// Bit 4 of each row is the leftmost pixel.
/// </summary>
internal static class BitmapFont
{
  public const int GlyphWidth = 5;
  public const int GlyphHeight = 7;
  public const int Advance = 6;

  private static readonly Dictionary<char, byte[]> Glyphs = new()
  {
    [' '] = [0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00],
    ['-'] = [0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00],
    ['/'] = [0x01, 0x02, 0x02, 0x04, 0x08, 0x08, 0x10],
    ['@'] = [0x0E, 0x11, 0x15, 0x15, 0x16, 0x10, 0x0E],
    ['0'] = [0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E],
    ['1'] = [0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E],
    ['2'] = [0x0E, 0x11, 0x01, 0x06, 0x08, 0x10, 0x1F],
    ['3'] = [0x0E, 0x11, 0x01, 0x06, 0x01, 0x11, 0x0E],
    ['4'] = [0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02],
    ['5'] = [0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E],
    ['6'] = [0x0E, 0x10, 0x10, 0x1E, 0x11, 0x11, 0x0E],
    ['7'] = [0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08],
    ['8'] = [0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E],
    ['9'] = [0x0E, 0x11, 0x11, 0x0F, 0x01, 0x01, 0x0E],
    ['m'] = [0x00, 0x00, 0x1B, 0x15, 0x15, 0x11, 0x11],
    ['p'] = [0x00, 0x00, 0x1E, 0x11, 0x1E, 0x10, 0x10],
    ['x'] = [0x00, 0x00, 0x11, 0x0A, 0x04, 0x0A, 0x11]
  };

  public static void Draw(Image<Rgb24> image, string text, int x, int y, Rgb24 color)
  {
    foreach (char ch in text)
    {
      if (!Glyphs.TryGetValue(ch, out byte[]? rows))
        throw new InvalidOperationException($"Corpus font has no glyph for '{ch}'.");

      for (int row = 0; row < GlyphHeight; row++)
      {
        byte bits = rows[row];
        for (int col = 0; col < GlyphWidth; col++)
        {
          if ((bits & (0x10 >> col)) == 0)
            continue;

          int px = x + col;
          int py = y + row;
          if ((uint)px < (uint)image.Width && (uint)py < (uint)image.Height)
            image[px, py] = color;
        }
      }

      x += Advance;
    }
  }
}
